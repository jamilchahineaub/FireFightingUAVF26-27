for case in ('full', 'empty'):
    h = MASS[case]['cg_pct_mac'] / 100
    say(f'- {case}: CG at {100 * h:.1f} % MAC, static margin {100 * (h_n - h):.0f} % MAC (plugin model {100 * (h_n_plugin - h):.0f} %)')
