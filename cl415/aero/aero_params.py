"""step 4a: gazebo LiftDrag parameters and propulsion numbers, with the working shown

reads cad/geometry.json (areas, hinge lines, chord ratios) and mass/mass_props.json (cg, weight).
writes aero/aero_params.json (consumed by tools/export_description.py) and aero/report.md.

model: gz-sim LiftDrag (Harmonic). per element it computes, at the cp,
    alpha = a0 + (angle between the local flow and the forward vector, in the forward/upward plane)
    cl = cla * alpha            (cla_stall slope past alpha_stall), plus control_joint_rad_to_cl * delta
    cd = |cda * alpha|          (cda_stall past alpha_stall)
    cm = cma * alpha + cm_delta * delta, applied as cm * q * S (no chord factor in the plugin)
so a0 carries incidence and zero-lift angle, and cla/cda are the finite-wing values.

run from the project root:  .venv/Scripts/python aero/aero_params.py
"""
