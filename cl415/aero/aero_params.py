D = A['props']['diameter']
CT0, CP0 = 0.085, 0.045
RPM_MAX = 8500.0
n_max = RPM_MAX / 60
w_max = 2 * math.pi * n_max
T_max = CT0 * RHO * n_max ** 2 * D ** 4
kT = T_max / w_max ** 2
Q_T = (CP0 / (2 * math.pi)) * D / CT0
P_max = CP0 * RHO * n_max ** 3 * D ** 5
say('## Propulsion (MulticopterMotorModel, one per propeller)')
say()
